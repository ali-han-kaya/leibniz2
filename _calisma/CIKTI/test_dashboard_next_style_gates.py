PRETTIER_BIN = REPO / "apps" / "dashboard-next" / "node_modules" / ".bin" / "prettier"
NODE_MODULES = REPO / "apps" / "dashboard-next" / "node_modules"
MANIFEST = HERE / "check_unit_tests.list"
