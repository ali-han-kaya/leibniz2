# ── sahte repo kurulumu ─────────────────────────────────────────────────────

def _fake_repo() -> pathlib.Path:
    """Gate scriptinin REPO'yu kendi konumundan türettiği sahte ağaç."""
    td = pathlib.Path(tempfile.mkdtemp())
    (td / "_calisma" / "CIKTI").mkdir(parents=True)
    shutil.copy(PRETTIER_GATE, td / "_calisma" / "CIKTI" / PRETTIER_GATE.name)
    # prettier config'i dosya yolundan yukarı doğru arar; kopyalanmazsa
    # vakalar builtin default'larla (semi'siz) koşardı.
    shutil.copy(REPO / ".prettierrc", td / ".prettierrc")
    if NODE_MODULES.is_dir():
        link = td / "apps" / "dashboard-next" / "node_modules"
        link.parent.mkdir(parents=True)
        try:
            link.symlink_to(NODE_MODULES, target_is_directory=True)
        except OSError:
            pass
    return td


# Sahte prisma CLI: CI'daki `npx prisma generate` yerine geçer. Çağrıyı ve
# DATABASE_URL'i loglar, sonra generated/ ağacını CI'ın assert'lerini geçecek
# şekilde yazar (FAKE_PRISMA_MODE=empty ile hiçbir şey yazmayan varyant).
FAKE_PRISMA_SCRIPT = (
    '#!/usr/bin/env bash\n'
    'printf "%s|%s\\n" "$*" "${DATABASE_URL:-}" >> "$FAKE_PRISMA_LOG"\n'
    'if [ "${FAKE_PRISMA_MODE:-valid}" = "empty" ]; then exit "${FAKE_PRISMA_EXIT:-0}"; fi\n'
    'mkdir -p generated/internal generated/models\n'
    'printf "// code generated by Prisma\\nexport const x = 1;\\n" > generated/client.ts\n'
    'printf "export const c = 1;\\n" > generated/internal/class.ts\n'
    'printf "export enum E {}\\n" > generated/enums.ts\n'
    'printf "export const a = 1;\\n" > generated/models/a.ts\n'
    'printf "export const b = 1;\\n" > generated/models/b.ts\n'
    'exit "${FAKE_PRISMA_EXIT:-0}"\n'
)


def _write_prisma_client(generated: pathlib.Path, files=5) -> None:
    """CI'ın assert'lerini geçen generated/ ağacı (bayat varyant için azaltılır)."""
    (generated / "internal").mkdir(parents=True, exist_ok=True)
    (generated / "client.ts").write_text(
        "// code generated by Prisma\nexport const x = 1;\n", encoding="utf-8")
    (generated / "internal" / "class.ts").write_text("export const c = 1;\n", encoding="utf-8")
    (generated / "enums.ts").write_text("export enum E {}\n", encoding="utf-8")
    for i in range(max(0, files - 3)):
        (generated / f"extra{i}.ts").write_text("export const e = 1;\n", encoding="utf-8")


def _fake_typecheck_repo(exit_code=0, with_tsc=True, with_tsconfig=True,
                         with_trend_db=True, prisma_client=True,
                         generated_files=5) -> pathlib.Path:
    """Kapının dört katmanını da koşturabilen sahte ağaç.

    trend-db/Prisma kurulumu CI ön-koşulunun karşılığıdır; `prisma_client`
    yanlışsa generated/ yoktur ve kapı `prisma generate` yolunu koşar.
    """
    td = pathlib.Path(tempfile.mkdtemp())
    (td / "_calisma" / "CIKTI").mkdir(parents=True)
    gate = td / "_calisma" / "CIKTI" / TYPECHECK_GATE.name
    shutil.copy(TYPECHECK_GATE, gate)
    gate.chmod(gate.stat().st_mode | stat.S_IEXEC)
    app = td / "apps" / "dashboard-next"
    app.mkdir(parents=True)
    if with_tsconfig:
        (app / "tsconfig.json").write_text("{}\n", encoding="utf-8")
    if with_tsc:
        bin_dir = app / "node_modules" / ".bin"
        bin_dir.mkdir(parents=True)
        fake = bin_dir / "tsc"
        # Args + "tsc koşarken Prisma istemcisi var mıydı": ikincisi kapının
        # generate adımını tsc'DEN ÖNCE koşturduğunu kanıtlar.
        fake.write_text(
            '#!/usr/bin/env bash\n'
            'printf "%s\\n" "$*" >> "$FAKE_TSC_LOG"\n'
            'app="$(cd "$(dirname "$0")/../.." && pwd)"\n'
            'if [ -s "$app/../trend-db/generated/client.ts" ]; then\n'
            '  printf "client=yes\\n" >> "$FAKE_TSC_CLIENT_LOG"\n'
            'else\n'
            '  printf "client=no\\n" >> "$FAKE_TSC_CLIENT_LOG"\n'
            'fi\n'
            'exit "${FAKE_TSC_EXIT:-0}"\n', encoding="utf-8")
        fake.chmod(fake.stat().st_mode | stat.S_IEXEC)
    if with_trend_db:
        trend_db = td / "apps" / "trend-db"
        (trend_db / "prisma").mkdir(parents=True)
        (trend_db / "prisma" / "schema.prisma").write_text(
            "model Run { id Int @id }\n", encoding="utf-8")
        (trend_db / "node_modules" / "@prisma" / "client").mkdir(parents=True)
        prisma_bin = trend_db / "node_modules" / ".bin" / "prisma"
        prisma_bin.parent.mkdir(parents=True, exist_ok=True)
        prisma_bin.write_text(FAKE_PRISMA_SCRIPT, encoding="utf-8")
        prisma_bin.chmod(prisma_bin.stat().st_mode | stat.S_IEXEC)
        if prisma_client:
            _write_prisma_client(trend_db / "generated", generated_files)
    return td


def _run(cmd, cwd=None, env=None, timeout=120) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                          cwd=cwd, env=env)


# `next build` katmanı için sahte npm: komutu loglar, istenirse tracked
# dosyaları Next gibi yeniden yazar. Gerçek ağaçta 20-30 sn'lik build
# koşmadan boru hattının tamamı (komut, restore, çıkış kodu) sınanır.
FAKE_NPM_SCRIPT = (
    '#!/usr/bin/env bash\n'
    'printf "%s\\n" "$*" >> "$FAKE_NPM_LOG"\n'
    'if [ "${FAKE_NPM_MUTATE:-0}" = "1" ]; then\n'
    '  printf "// rewritten by next build\\n" > next-env.d.ts\n'
    '  printf "{\\"rewritten\\":true}\\n" > tsconfig.json\n'
    'fi\n'
    'exit "${FAKE_NPM_EXIT:-0}"\n'
)


def _fake_build_repo(**kwargs) -> pathlib.Path:
    """Sahte ağaca build katmanını (test-d koşucusu + next + npm) ekler.

    Trend-db/Prisma kurulumu artık `_fake_typecheck_repo` içindedir: kapı
    Prisma adımını tsc'DEN ÖNCE koşturduğu için o ön-koşul her iki katmanın
    ortak zeminidir.
    """
    td = _fake_typecheck_repo(**kwargs)
    app = td / "apps" / "dashboard-next"
    test_d = app / "test-d"
    test_d.mkdir()
    (test_d / "run_type_tests.py").write_text(
        'import sys\nprint("OK")\nsys.exit(0)\n', encoding="utf-8")
    (app / "package.json").write_text(
        '{"scripts": {"build": "next build"}}\n', encoding="utf-8")
    next_bin = app / "node_modules" / ".bin" / "next"
    next_bin.write_text('#!/usr/bin/env bash\nexit 0\n', encoding="utf-8")
    next_bin.chmod(next_bin.stat().st_mode | stat.S_IEXEC)
    (app / "next-env.d.ts").write_text("// baseline next-env\n", encoding="utf-8")
    bin_dir = td / "bin"
    bin_dir.mkdir()
    npm = bin_dir / "npm"
    npm.write_text(FAKE_NPM_SCRIPT, encoding="utf-8")
    npm.chmod(npm.stat().st_mode | stat.S_IEXEC)
    return td


