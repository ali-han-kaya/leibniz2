# ── check-dashboard-typecheck ───────────────────────────────────────────────

class DashboardTypecheckGateTest(unittest.TestCase):
    def _run_gate(self, td, exit_code=0, extra_env=None):
        log = td / "tsc-args.log"
        env = dict(os.environ, FAKE_TSC_LOG=str(log),
                   FAKE_TSC_EXIT=str(exit_code),
                   FAKE_TSC_CLIENT_LOG=str(td / "tsc-client.log"))
        if extra_env:
            env.update(extra_env)
        gate = td / "_calisma" / "CIKTI" / TYPECHECK_GATE.name
        r = _run(["bash", str(gate)], env=env)
        args = log.read_text(encoding="utf-8").strip() if log.is_file() else None
        return r, args

    def _run_build_gate(self, td, npm_exit=0, mutate=False, prisma_mode="valid",
                        prisma_exit=0):
        env = {
            "PATH": str(td / "bin") + os.pathsep + os.environ.get("PATH", ""),
            "FAKE_NPM_LOG": str(td / "npm-args.log"),
            "FAKE_NPM_EXIT": str(npm_exit),
            "FAKE_NPM_MUTATE": "1" if mutate else "0",
            "FAKE_PRISMA_LOG": str(td / "prisma-args.log"),
            "FAKE_PRISMA_MODE": prisma_mode,
            "FAKE_PRISMA_EXIT": str(prisma_exit),
        }
        return self._run_gate(td, extra_env=env)[0]

    def test_clean_typecheck_passes(self):
        td = _fake_typecheck_repo(exit_code=0)
        try:
            r, args = self._run_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("OK", r.stdout)
            self.assertEqual(args, "--noEmit")
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_type_error_fails_closed(self):
        td = _fake_typecheck_repo(exit_code=1)
        try:
            r, _ = self._run_gate(td, exit_code=1)
            self.assertNotEqual(r.returncode, 0)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_emit_is_never_requested(self):
        """`--noEmit` dışında argüman yok: kapı çıktı üretemez (READ-ONLY)."""
        td = _fake_typecheck_repo()
        try:
            _, args = self._run_gate(td)
            self.assertIsNotNone(args)
            self.assertNotIn("--outDir", args)
            self.assertNotIn("--emit", args)
            self.assertFalse((td / "apps/dashboard-next/tsconfig.tsbuildinfo").exists())
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_missing_tsc_skips(self):
        td = _fake_typecheck_repo(with_tsc=False)
        try:
            r, args = self._run_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("SKIP", r.stdout)
            self.assertIsNone(args)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_missing_tsconfig_skips(self):
        td = _fake_typecheck_repo(with_tsconfig=False)
        try:
            r, args = self._run_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("SKIP", r.stdout)
            self.assertIsNone(args)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_build_runs_same_command_as_ci(self):
        """tsc sonrası CI'daki `npm run build` aynen koşar."""
        td = _fake_build_repo()
        try:
            r = self._run_build_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            log = (td / "npm-args.log").read_text(encoding="utf-8")
            self.assertEqual(log.strip(), "run build")
            self.assertIn("next build OK", r.stdout)
            self.assertIn("tsc + tip-testleri=OK + next build", r.stdout)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_build_failure_fails_closed(self):
        td = _fake_build_repo()
        try:
            r = self._run_build_gate(td, npm_exit=1)
            self.assertNotEqual(r.returncode, 0)
            self.assertIn("next build FAIL", r.stdout + r.stderr)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_build_skips_when_next_missing(self):
        """Ortam-bağımlı SKIP: tsc var ama next yok — build katmanı atlanır."""
        td = _fake_typecheck_repo()
        try:
            r, _ = self._run_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("SKIP (build katmanı)", r.stdout)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_build_restores_tracked_files_it_rewrites(self):
        """Next'in yeniden yazdığı next-env.d.ts/tsconfig.json geri alınır."""
        td = _fake_build_repo()
        app = td / "apps" / "dashboard-next"
        try:
            r = self._run_build_gate(td, mutate=True)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertEqual((app / "next-env.d.ts").read_text(encoding="utf-8"),
                             "// baseline next-env\n")
            self.assertEqual((app / "tsconfig.json").read_text(encoding="utf-8"),
                             "{}\n")
            self.assertIn("geri alındı", r.stdout)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_missing_trend_db_deps_skips_gate(self):
        """trend-db kurulmamışsa kapı SKIP: ortam-yok ≠ kod-bozuk."""
        td = _fake_build_repo(with_trend_db=False)
        try:
            r = self._run_build_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("trend-db bağımlılıkları eksik — SKIP", r.stdout)
            self.assertFalse((td / "npm-args.log").exists())
            self.assertFalse((td / "tsc-args.log").exists())
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_prisma_generate_runs_before_tsc(self):
        """Sıra kanıtı: tsc koştuğunda generated istemci ARTIK yerinde olmalı.

        CI'da `prisma generate` build'den önce koşar; yerelde tsc ilk katman
        olduğu için generate ondan da önce gelmeli, yoksa istemcisiz ağaçta
        `lib/trend-db.ts` sahte TS2307 üretir.
        """
        td = _fake_build_repo(prisma_client=False)
        try:
            r = self._run_build_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertEqual(
                (td / "tsc-client.log").read_text(encoding="utf-8").strip(),
                "client=yes")
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_missing_prisma_client_is_generated_like_ci(self):
        """İstemci yoksa CI'ın yer tutucu DATABASE_URL'iyle generate koşar."""
        td = _fake_build_repo(prisma_client=False)
        try:
            r = self._run_build_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            log = (td / "prisma-args.log").read_text(encoding="utf-8").strip()
            self.assertIn("generate", log)
            self.assertIn("postgresql://ci:ci@127.0.0.1:5432/ci?sslmode=disable", log)
            self.assertIn("CI gibi üretiliyor", r.stdout)
            self.assertIn("next build OK", r.stdout)
        finally:
            shutil.rmtree(td, ignore_errors=True)

    def test_stale_prisma_client_is_regenerated(self):
        """CI'ın 5-dosya assert'ini geçmeyen artefakt bayat sayılır."""
        td = _fake_build_repo(generated_files=2)
        try:
            r = self._run_build_gate(td)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            log = (td / "prisma-args.log").read_text(encoding="utf-8").strip()
            self.assertIn("generate", log)
            generated = td / "apps" / "trend-db" / "generated"
            self.assertGreaterEqual(len(list(generated.rglob("*.ts"))), 5)
        finally:
            shutil.rmtree(td, ignore_errors=True)

