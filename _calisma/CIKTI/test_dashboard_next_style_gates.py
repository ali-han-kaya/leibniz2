WORKFLOW = REPO / ".github" / "workflows" / "verify.yml"
QUALITY_JOB = "quality-gates"
TOKENS_STEP = "Check design tokens (design-system ↔ dashboard bridge)"
TYPECHECK_CI_STEP = "Dashboard-next typecheck + type tests + build (fail-closed)"
FULL_OK = "check-dashboard-typecheck: OK (tsc + tip-testleri=OK + next build)"


def _quality_steps():
    import yaml  # repo venv'inde kurulu; CI'da da var

    wf = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
    steps = wf["jobs"][QUALITY_JOB]["steps"]
    return steps, {str(s.get("name", "")): s for s in steps}


def _run_typecheck_step_body(run, output, rc=0):
    """Adımın shell gövdesini sahte bir typecheck script'iyle GERÇEKTEN koş.

    Gerçek tsc/next gerekmez: adımın kendi çıktı-hükmü (tam OK satırı) sınanır.
    """
    td = pathlib.Path(tempfile.mkdtemp(prefix="quality-step-"))
    try:
        stub = td / "_calisma" / "CIKTI" / "check_dashboard_typecheck.sh"
        stub.parent.mkdir(parents=True)
        stub.write_text(
            "#!/usr/bin/env bash\n"
            "printf '%s\\n' \"$FAKE_OUT\"\n"
            "exit \"${FAKE_RC:-0}\"\n",
            encoding="utf-8")
        env = dict(os.environ)
        env["FAKE_OUT"] = output
        env["FAKE_RC"] = str(rc)
        return subprocess.run(["bash", "-c", run], cwd=str(td), env=env,
                              capture_output=True, text=True, timeout=60)
    finally:
        shutil.rmtree(td, ignore_errors=True)


class TestCiQualityGates(unittest.TestCase):
    """Yeni required job: pre-commit'e bağlı üç kapı PR'da ve fail-closed.

    `quality-gates` job'ı `check-design-tokens`, all-tracked Prettier ve
    `check-dashboard-typecheck` kapılarını TEK yuvada koşar. Bu sınıf
    adımların var olduğunu, advisory olmadığını ve SKIP çıktısının KIRMIZIya
    döndüğünü pinler — "keşfedildi ama ölçmedi" sessiz yeşili kapalı kalır.
    """

    def test_job_is_shaped_like_a_required_gate(self):
        import yaml

        wf = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
        job = wf["jobs"][QUALITY_JOB]
        self.assertIn("timeout-minutes", job)
        self.assertEqual((job.get("permissions") or {}).get("contents"), "read")
        self.assertNotIn("continue-on-error", job)
        for step in job["steps"]:
            self.assertFalse(step.get("continue-on-error"),
                             "%s advisory'ye çevrilmis" % step.get("name"))

    def test_design_token_step_runs_the_hook_command(self):
        _steps, named = _quality_steps()
        self.assertIn(TOKENS_STEP, named, "design-token CI adımı yok")
        self.assertIn("design-system/scripts/check_tokens.py",
                      named[TOKENS_STEP]["run"])

    def test_typecheck_step_runs_the_hook_script(self):
        _steps, named = _quality_steps()
        self.assertIn(TYPECHECK_CI_STEP, named)
        run = named[TYPECHECK_CI_STEP]["run"]
        self.assertIn("_calisma/CIKTI/check_dashboard_typecheck.sh", run)
        self.assertIn("set -euo pipefail", run)

    def test_typecheck_step_rejects_skip_and_partial_ok(self):
        run = _quality_steps()[1][TYPECHECK_CI_STEP]["run"]
        for bad in ("check-dashboard-typecheck: SKIP",
                    "check-dashboard-typecheck: tsc OK",
                    "check-dashboard-typecheck: OK (tsc + tip-testleri=SKIP + next build)"):
            proc = _run_typecheck_step_body(run, bad)
            self.assertNotEqual(proc.returncode, 0,
                                "SKIP/eksik katman YESIL sayildi: %r" % bad)

    def test_typecheck_step_passes_on_full_ok(self):
        run = _quality_steps()[1][TYPECHECK_CI_STEP]["run"]
        proc = _run_typecheck_step_body(run, FULL_OK)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_typecheck_step_propagates_real_failure(self):
        run = _quality_steps()[1][TYPECHECK_CI_STEP]["run"]
        proc = _run_typecheck_step_body(run, "tsc: error", rc=2)
        self.assertEqual(proc.returncode, 2, proc.stdout + proc.stderr)


