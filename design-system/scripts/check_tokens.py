TAILWIND_BRIDGE = REPO / "design-system" / "tailwind.css"
STRIPE_MIRROR = REPO / "design-system" / "stripe" / "tokens.css"
STRIPE_THEME = REPO / "design-system" / "stripe" / "theme.css"
