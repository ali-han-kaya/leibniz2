#!/usr/bin/env python3
"""check_tokens.py — verify design-system tokens match the dashboard.

Contracts (post-import):
1. preview.html must import design-system/tokens.css (link or @import).
2. Every custom property in tokens.css :root (dark) + [data-theme="light"]
   block appears verbatim in either the imported sheet or the HTML.
3. Every rgba tint in tokens.json must be resolvable via the token sheet
   (values kept verbatim — checked against tokens.css, not duplicated HTML).
4. The HTML must not contain a duplicate inline :root var block that would
   shadow the import (drift — two sources of truth).
5. apps/dashboard-next/app/globals.css must import design-system/tailwind.css
   (the generated Tailwind v4 bridge) and must NOT re-define any token name
   from tokens.css :root in its own :root block (shadow = drift).
6. design-system/tailwind.css :root block must equal tokens.css :root
   verbatim (the file is GENERATED by scripts/generate_tailwind.py;
   hand-edits break the bridge).
7. dashboard-next COPY DRIFT: the same walk that backs contract 5 also
   rejects (a) a token name re-declared in ANY style-rule block — a second
   :root, .dark, @media, @layer … not just the first :root the old regex
   could see, (b) a custom property whose literal value is verbatim a
   tokens.css value (a copy instead of a reference), and (c) a hard-coded
   colour literal in any custom property. Comments are stripped first, so
   prose mentioning `:root {` can neither trip nor mask a finding.
9. STRIPE TEMA VARYANTI (design-system/stripe/theme.css): meta/landing'in
   `data-theme="stripe"` varyantı GENERATED'dır. Kapı: dosya jeneratörle
   BİREBİR olmalı (elle drift yasak), tanımlar yalnız
   `:root[data-theme="stripe"]` kapsamında olmalı, jeneratörün
   REQUIRED_SLOTS'ünün tamamı bağlanmalı (eksik yuva = koyu palete sessiz
   geri dönüş), HDS ön-koşulları aynadaki (stripe/tokens.css) değerlerle
   birebir olmalı ve her yuva değeri en az bir `var(--hds-*)` referansı
   taşımalı (literal renk yasak).
8. dashboard-next PRESET BAĞIMSIZLIĞI + REFERANS KAPANIŞI: globals.css
   (a) shadcn preset CSS'i (@import "shadcn/…") DIŞARIDAN çekemez — tema
   yalnız design-system/tailwind.css köprüsünden ve repo-içi yuva
   eşlemesinden gelir, (b) stilde YAZIYLA verilmiş değer taşıyamaz (her
   custom property var()/calc() ile bağlanır; literal = kopya adayı),
   (c) her var(--X) referansı çözülebilir olmalı (tokens.css ya da aynı
   dosyada tanımlı yuva) — çürük/typo referans sessiz stil kaybıdır,
   (d) :root'ta tanımlı her renk yuvası @theme'de --color-<yuva> olarak
   yeniden sunulmalı (--radius istisna: yarıçap ölçeğini besler),
   (e) uygulama kaynağı preset-only utility (data-open: …, no-scrollbar,
   scroll-fade, shimmer) kullanamaz — preset silindiği için o sınıflar
   sessizce stilsiz kalır,
   (f) uygulama kaynağında koda gömülü RENK OLAMAZ: ne arbitrary renk
   utility'si (`bg-[#0e1116]`), ne ham hex/rgb/hsl literali (inline stil
   dahil), ne de Tailwind'ın varsayılan paleti (`bg-slate-900`,
   `text-white`) — üçü de köprü token'ını baypas eder ve temayı
   koyu/açık/stripe varyantlarında dondurur. Kapsam TÜM uygulama
   kaynağıdır (`.tsx .ts .jsx .js`) — yalnız globals.css değil,
   (g) globals.css DIŞINDAKİ her `.css` de aynı ham-renk taramasından
   geçer: yeni bir stil dosyası açmak, bir literali bu kapının dışına
   taşımanın en kolay yolu olurdu (@theme/@utility blokları burada da
   muaftır — onlar utility EŞLEMESİdir, belge custom property'si değil).

Exit 0 on match, 1 on drift.
"""
